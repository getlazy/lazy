/**
 * What a mid-turn tier switch does to a conversation's history.
 *
 * A tiered profile keeps ONE agent session across providers, so a request to
 * one tier carries assistant turns another provider wrote. The block type that
 * makes that unsafe is extended THINKING: Anthropic signs each `thinking` block
 * and verifies the signature when the block is sent back, and `redacted_thinking`
 * is an encrypted payload only Anthropic can read.
 *
 * VERIFIED (2026-10-01) against Anthropic's documentation —
 * docs.claude.com "Building with extended thinking", platform.claude.com
 * "Thinking in tool and multi-turn workflows", "Adaptive thinking" and
 * "Preserved thinking":
 *  - the `signature` verifies that a thinking block was generated by Claude;
 *  - thinking blocks from EARLIER assistant turns may be omitted;
 *  - a tool-use loop is ONE assistant turn and runs in one thinking mode;
 *    thinking cannot be toggled inside it;
 *  - in MANUAL mode (`thinking.type = "enabled"`) the final assistant message of
 *    an open tool loop must start with its thinking block — older behaviour is a
 *    400, current behaviour is that the API silently disables thinking (and may
 *    strip blocks itself) for that request. ADAPTIVE thinking has no such
 *    requirement;
 *  - on newer models (Opus 5.5) thinking cannot be disabled, and a thinking
 *    signature is bound to the conversation prefix it was produced from, so a
 *    block kept behind stripped or rewritten history can be refused.
 *
 * Why not "strip only blocks with a foreign signature": a signature is opaque,
 * lazy cannot tell whose it is, and prefix binding means even a genuine
 * Anthropic block can fail once anything before it was stripped. So the
 * conservative path: once a task's history has crossed providers, every request
 * on its tiered profile goes out with ALL thinking blocks removed. In manual
 * mode, while a tool loop is open and its final assistant message (after
 * stripping) does not start with a thinking block — whether lazy removed it or
 * another provider never wrote one — `thinking` is turned off for the request,
 * so the whole rest of that loop runs in one mode. The next NEW user message
 * starts a fresh turn and thinking is left on again. Adaptive thinking is never
 * turned off. NOT VERIFIED: what Fireworks' or Ollama's Anthropic-compatible
 * endpoints do with thinking blocks.
 */

export interface StripResult {
  body: Record<string, unknown>;
  /** Thinking blocks removed. */
  stripped: number;
  /** True when `thinking` was turned off for this request. */
  thinkingDisabled: boolean;
}

const THINKING_TYPES = new Set(['thinking', 'redacted_thinking']);

const isThinkingBlock = (block: unknown): boolean =>
  !!block && typeof block === 'object' && THINKING_TYPES.has((block as { type?: string }).type ?? '');

/** Remove every thinking block from an Anthropic Messages request body. Pure. */
export function stripThinkingHistory(body: Record<string, unknown>): StripResult {
  const messages = body.messages;
  if (!Array.isArray(messages)) return { body, stripped: 0, thinkingDisabled: false };
  let stripped = 0;
  const nextMessages = messages.map((m) => {
    if (!m || typeof m !== 'object') return m;
    const content = (m as { content?: unknown }).content;
    if (!Array.isArray(content)) return m;
    const kept = content.filter((block) => {
      const drop = isThinkingBlock(block);
      if (drop) stripped++;
      return !drop;
    });
    if (kept.length === content.length) return m;
    // An assistant message whose only content was thinking would become empty,
    // which the API refuses; a placeholder text block keeps the turn order.
    return { ...(m as object), content: kept.length ? kept : [{ type: 'text', text: '(thinking omitted)' }] };
  });
  const next: Record<string, unknown> = stripped > 0 ? { ...body, messages: nextMessages } : { ...body };
  let thinkingDisabled = false;
  const thinking = body.thinking as { type?: string } | undefined;
  // Manual mode only: adaptive thinking carries no final-block requirement.
  if (thinking?.type === 'enabled' && openLoopWithoutFinalThinking(nextMessages)) {
    delete next.thinking;
    thinkingDisabled = true;
  }
  if (stripped === 0 && !thinkingDisabled) return { body, stripped: 0, thinkingDisabled: false };
  return { body: next, stripped, thinkingDisabled };
}

/**
 * Is a tool-use loop still open, with a final assistant message that does not
 * start with a thinking block? Open = some user message after that assistant
 * message carries a `tool_result` (Claude Code adds reminder text beside tool
 * results, so "only tool results" is not the test). A user message with no
 * `tool_result` starts a new turn.
 */
function openLoopWithoutFinalThinking(messages: unknown[]): boolean {
  let lastAssistant = -1;
  for (let i = messages.length - 1; i >= 0; i--) {
    if ((messages[i] as { role?: string } | null)?.role === 'assistant') { lastAssistant = i; break; }
  }
  if (lastAssistant < 0) return false;
  const after = messages.slice(lastAssistant + 1) as Array<{ role?: string; content?: unknown } | null>;
  const users = after.filter((m) => m?.role === 'user');
  // Nothing after it: an assistant prefill continuing the same turn.
  const open = users.length === 0 || users.every((m) =>
    Array.isArray(m?.content) && m!.content.some((b) => (b as { type?: string } | null)?.type === 'tool_result'));
  if (!open) return false;
  const content = (messages[lastAssistant] as { content?: unknown }).content;
  const first = Array.isArray(content) ? content[0] : null;
  return !isThinkingBlock(first);
}
